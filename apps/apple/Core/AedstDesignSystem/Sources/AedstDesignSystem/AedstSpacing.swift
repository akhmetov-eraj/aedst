/// 4pt-grid spacing scale — mirrors the `spacing-*` tokens in
/// `apps/web`'s Tailwind config and the `Dimens` used across
/// `apps/android/core/ui`, so a designer's spec reads the same number on
/// every platform.
public enum AedstSpacing {
    public static let xxs: Double = 2
    public static let xs: Double = 4
    public static let sm: Double = 8
    public static let md: Double = 16
    public static let lg: Double = 24
    public static let xl: Double = 32
    public static let xxl: Double = 48
    public static let xxxl: Double = 64
}
