// Command gen-config-docs writes docs/content/server/config.md from the `env:`
// tags of config.Config, so the reference cannot drift from the code. The
// descriptions are the field doc comments (go/parser); `task docs:config`
// regenerates it and `task docs:config:check` fails when it is stale.
package main

import (
	"context"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"log/slog"
	"os"
	"path/filepath"
	"reflect"
	"strings"

	"github.com/aedst/server/internal/platform/config"
)

type row struct {
	env, typ, def, doc string
	required           bool
}

type section struct {
	name string
	rows []row
}

func main() {
	if err := run(); err != nil {
		slog.ErrorContext(context.Background(), "gen-config-docs", "err", err)
		os.Exit(1)
	}
}

func run() error {
	const out = "../../docs/content/server/config.md" // run from apps/server (task docs:config)
	docs, err := fieldDocs("internal/platform/config")
	if err != nil {
		return err
	}
	var sections []*section
	collect(reflect.TypeOf(config.Config{}), "Core", docs, &sections)

	var sb strings.Builder
	sb.WriteString("---\ntitle: \"Configuration reference\"\ndescription: \"Every environment variable the server reads, generated from internal/platform/config.\"\n---\n\n")
	sb.WriteString("# Configuration reference\n\n")
	sb.WriteString("<!-- Generated by `task docs:config` from the `env:` tags of config.Config. Do not edit. -->\n\n")
	sb.WriteString("Every variable the server reads. Required variables fail startup when missing. The Helm chart renders each of them from `values.yaml` (a test enforces it), and `.env.example` documents each for local runs. Cross-field rules live in `Config.Validate`.\n")
	sb.WriteString("\nOpen-ended family (not listed below): `AEDST_DATABASE_URL_<MODULE>` and `AEDST_DATABASE_URL_<MODULE>_JOBS` point one module at its own database (database-per-module); an unknown module name fails startup.\n")
	for _, sec := range sections {
		if len(sec.rows) == 0 {
			continue
		}
		fmt.Fprintf(&sb, "\n## %s\n\n| Variable | Type | Default | Description |\n|---|---|---|---|\n", sec.name)
		for _, r := range sec.rows {
			def := "`" + r.def + "`"
			switch {
			case r.required:
				def = "**required**"
			case r.def == "":
				def = "(empty)"
			}
			fmt.Fprintf(&sb, "| `%s` | %s | %s | %s |\n", r.env, r.typ, def, cell(r.doc))
		}
	}
	if err := os.WriteFile(out, []byte(sb.String()), 0o600); err != nil {
		return fmt.Errorf("write %s: %w", out, err)
	}
	return nil
}

func cell(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.ReplaceAll(s, "|", "\\|")
}

// collect walks the struct; each nested struct becomes its own section.
func collect(t reflect.Type, name string, docs map[string]string, sections *[]*section) {
	sec := &section{name: name}
	*sections = append(*sections, sec)
	for i := range t.NumField() {
		f := t.Field(i)
		tag, _, _ := strings.Cut(f.Tag.Get("env"), ",")
		if f.Type.Kind() == reflect.Struct && tag == "" {
			collect(f.Type, strings.TrimSuffix(f.Type.Name(), "Config"), docs, sections)
			continue
		}
		if tag == "" || tag == "-" {
			continue
		}
		sec.rows = append(sec.rows, row{
			env:      tag,
			typ:      typeName(f.Type),
			def:      f.Tag.Get("envDefault"),
			doc:      docs[t.Name()+"."+f.Name],
			required: strings.Contains(f.Tag.Get("env"), ",required"),
		})
	}
}

func typeName(t reflect.Type) string {
	switch k := t.Kind(); {
	case k == reflect.Map:
		return "map"
	case k == reflect.Slice:
		return "list"
	case k == reflect.Bool:
		return "bool"
	case k >= reflect.Int && k <= reflect.Int64:
		return "int"
	default:
		return "string"
	}
}

// fieldDocs maps "Struct.Field" to the field's doc comment (or trailing comment).
func fieldDocs(dir string) (map[string]string, error) {
	fset := token.NewFileSet()
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, fmt.Errorf("glob %s: %w", dir, err)
	}
	docs := map[string]string{}
	for _, file := range files {
		if strings.HasSuffix(file, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, file, nil, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("parse %s: %w", file, err)
		}
		ast.Inspect(f, func(n ast.Node) bool {
			ts, ok := n.(*ast.TypeSpec)
			if !ok {
				return true
			}
			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				return true
			}
			for _, fld := range st.Fields.List {
				text := ""
				if fld.Doc != nil {
					text = fld.Doc.Text()
				} else if fld.Comment != nil {
					text = fld.Comment.Text()
				}
				for _, name := range fld.Names {
					docs[ts.Name.Name+"."+name.Name] = text
				}
			}
			return true
		})
	}
	return docs, nil
}
