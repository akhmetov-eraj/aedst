#!/usr/bin/env bash
# Blocking clang-tidy gate for Modules/ and App/ with a checked-in baseline.
#
#   ./scripts/run-clang-tidy.sh [build-dir]           # gate (what CI runs); default build/clang-debug
#   ./scripts/run-clang-tidy.sh --update-baseline [build-dir]
#                                                   # rewrite scripts/clang-tidy-baseline.txt from the
#                                                   # current findings (only ever to SHRINK it in PRs)
#
# How it works
#   1. run-clang-tidy --warnings-as-errors='*' over first-party translation units
#      (compile_commands.json from a *clang* preset: GCC-only warning flags would
#      make clang-tidy report unknown-warning-option noise).
#   2. Every diagnostic `path:line:col: (warning|error): ... [check]` is reduced to
#      `relative/path:check`. Pairs listed in scripts/clang-tidy-baseline.txt are known
#      debt and ignored; ANYTHING else fails the run.
#   3. Baseline entries that no longer fire are reported as STALE (delete them; with
#      AEDST_TIDY_STRICT_BASELINE=1 a stale entry also fails, so the baseline can
#      only shrink).
#
# Baseline format (scripts/clang-tidy-baseline.txt): one `path:check` per line,
# path relative to apps/desktop, check may be a full name or `*`; `#` comments.
#
# Env: RUN_CLANG_TIDY (binary, default run-clang-tidy[-N]), AEDST_TIDY_LOG (log file,
#      default clang-tidy.log), AEDST_TIDY_JOBS (default: all cores),
#      AEDST_TIDY_BASELINE (baseline file, default scripts/clang-tidy-baseline.txt),
#      AEDST_TIDY_ONLY_WINDOWS=1 (analyse only the translation units with Windows-only code: for the MSVC compile
#      database in CI, because the Linux clang database never compiles them; desktop-ci "clang-tidy (msvc database)"),
#      AEDST_TIDY_EXTRA_ARGS (extra run-clang-tidy arguments, e.g. "-extra-arg=/clang:-Wno-unknown-argument").
#
# MSVC database (build/msvc-debug): clang-tidy sees cl.exe commands and switches to clang-cl mode. UNVERIFIED on a
# real run: the first CI run decides whether extra arguments are needed.
set -uo pipefail

cd "$(dirname "$0")/.."
root="$(pwd)"
baseline="${AEDST_TIDY_BASELINE:-scripts/clang-tidy-baseline.txt}"
# Windows (Git Bash): the compile database and clang-tidy output use D:/a/... paths, not /d/a/...
root_native="$( (pwd -W 2>/dev/null) || pwd)"

update=0
if [ "${1:-}" = "--update-baseline" ]; then update=1; shift; fi
build_dir="${1:-build/clang-debug}"
log="${AEDST_TIDY_LOG:-clang-tidy.log}"

if [ ! -f "$build_dir/compile_commands.json" ]; then
  echo "error: $build_dir/compile_commands.json not found. Configure first: cmake --preset clang-debug" >&2
  exit 2
fi

runner="${RUN_CLANG_TIDY:-}"
if [ -z "$runner" ]; then
  for c in run-clang-tidy run-clang-tidy-19 run-clang-tidy-18 run-clang-tidy-17; do
    command -v "$c" >/dev/null 2>&1 && { runner="$c"; break; }
  done
fi
if [ -z "$runner" ]; then
  echo "error: run-clang-tidy not found (apt install clang-tidy clang-tools, or set RUN_CLANG_TIDY)." >&2
  exit 127
fi

jobs="${AEDST_TIDY_JOBS:-$( (command -v nproc >/dev/null && nproc) || sysctl -n hw.ncpu 2>/dev/null || echo 2)}"

# Only first-party sources. Anchoring on the source root keeps build/**/*_autogen and
# generated protobuf (under build/) out even though their path contains "App/".
files_regex="^${root_native}/(Modules|App)/"
if [ "${AEDST_TIDY_ONLY_WINDOWS:-0}" = "1" ]; then
  # Translation units with Windows-only code: a _WIN32/Q_OS_WIN guard or the Windows toast adapter.
  win_files=$(grep -rlE '_WIN32|Q_OS_WIN|AEDST_PLATFORM_HAS_WINDOWS' Modules App --include=*.cpp 2>/dev/null \
    | grep -vE '/(tests|bench)/' | sed 's/[.[*^$()+?{|]/\\&/g' | paste -sd'|' -)
  [ -n "$win_files" ] || { echo "OK: no Windows-only translation units."; exit 0; }
  files_regex="^${root_native}/(${win_files})\$"
fi
runner_cmd=("$runner"); case "$runner" in *.py) runner_cmd=(python "$runner") ;; esac

# shellcheck disable=SC2086
"${runner_cmd[@]}" -p "$build_dir" -quiet -j "$jobs" \
  -warnings-as-errors='*' ${AEDST_TIDY_EXTRA_ARGS:-} \
  "$files_regex" >"$log" 2>&1
tidy_status=$?
# Windows output uses backslashes: normalise so the path reduction below sees one shape.
sed -i 's#\\#/#g' "$log"

# Reduce diagnostics to "relative/path:check" pairs.
found=$(grep -E ': (warning|error): .*\[[A-Za-z0-9_.,-]+\]$' "$log" \
  | sed -E "s#^(${root}|${root_native})/##I; s#^\./##" \
  | sed -E 's#^([^:]+):[0-9]+:[0-9]+: (warning|error): .*\[([A-Za-z0-9_.,-]+)\]$#\1:\3#' \
  | sed -E 's/,-warnings-as-errors//' \
  | sort -u || true)

if [ "$update" -eq 1 ]; then
  {
    echo "# clang-tidy baseline: known findings that do not fail CI. One path:check per line."
    echo "# Regenerated by scripts/run-clang-tidy.sh --update-baseline. This file may only shrink"
    echo "# in review (see CLANG_TIDY_BASELINE.md). Paths are relative to apps/desktop."
    [ -n "$found" ] && echo "$found"
  } >"$baseline"
  echo "baseline rewritten: $(printf '%s\n' "$found" | grep -c . || true) entries -> $baseline"
  exit 0
fi

# Load baseline (strip comments/blank lines).
entries=$(grep -vE '^[[:space:]]*(#|$)' "$baseline" 2>/dev/null || true)

new=""
while IFS= read -r pair; do
  [ -z "$pair" ] && continue
  path="${pair%%:*}"; check="${pair#*:}"
  # A finding may list several comma-separated checks; ignore only if all are baselined.
  ignored_all=1
  IFS=',' read -r -a checks <<< "$check"
  for c in "${checks[@]}"; do
    if printf '%s\n' "$entries" | grep -Fxq "$path:$c" || printf '%s\n' "$entries" | grep -Fxq "$path:*"; then
      :
    else
      ignored_all=0
    fi
  done
  [ "$ignored_all" -eq 0 ] && new="${new}${pair}"$'\n'
done <<< "$found"

# Stale baseline entries.
stale=""
while IFS= read -r e; do
  [ -z "$e" ] && continue
  path="${e%%:*}"; check="${e#*:}"
  if [ "$check" = "*" ]; then
    printf '%s\n' "$found" | grep -q "^$(printf '%s' "$path" | sed 's/[.[\*^$]/\\&/g'):" || stale="${stale}${e}"$'\n'
  else
    printf '%s\n' "$found" | grep -Fq "$path:" && printf '%s\n' "$found" | grep -F "$path:" | grep -Eq "(:|,)$(printf '%s' "$check" | sed 's/[.[\*^$]/\\&/g')(,|$)" \
      || stale="${stale}${e}"$'\n'
  fi
done <<< "$entries"

status=0
if [ -n "$new" ]; then
  echo "::error::clang-tidy: findings not covered by $baseline (fix them; do NOT add to the baseline):"
  printf '%s' "$new"
  echo "(full output: $log)"
  status=1
fi
if [ -n "$stale" ]; then
  echo "::warning::clang-tidy: STALE baseline entries (no longer reported; delete them from $baseline):"
  printf '%s' "$stale"
  [ "${AEDST_TIDY_STRICT_BASELINE:-0}" = "1" ] && status=1
fi

# run-clang-tidy failed for a reason that produced no parsable finding (crash, missing
# compile command, clang-diagnostic errors are parsed above): do not report a false green.
if [ "$tidy_status" -ne 0 ] && [ -z "$found" ]; then
  echo "::error::run-clang-tidy exited $tidy_status without parsable findings; see $log" >&2
  tail -n 30 "$log" >&2
  status=1
fi

[ "$status" -eq 0 ] && echo "OK: clang-tidy clean (baseline entries in use: $(printf '%s\n' "$entries" | grep -c . || true))."
exit "$status"
